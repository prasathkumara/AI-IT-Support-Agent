"""Ticket domain model (employee ticket creation).

NEW CONCEPT: model vs schema (same split as conversation.py)
    A *model* describes how a ticket looks INSIDE the app and the database.
    A *schema* (app/schemas/ticket.py) describes what crosses the API boundary.
    Keeping them separate lets us change internals without breaking the API.

A "ticket" is a support request an employee raises when the AI could not solve
their issue (or when they skip the AI and report it directly). The IT team later
assigns and resolves it (those admin actions come in a later slice).

The field names and the allowed enum values deliberately MIRROR the frontend's
`Ticket` type (frontend/types/index.ts) so the two stay in lockstep.
"""

from datetime import datetime, timezone
from enum import Enum

from pydantic import BaseModel, Field


class TicketStatus(str, Enum):
    """Lifecycle of a ticket. New tickets always start OPEN.

    Using an Enum (a fixed set of values) prevents typos — only these exact
    strings are valid. Values match the frontend's TicketStatus union.
    """

    OPEN = "Open"
    IN_PROGRESS = "In Progress"
    RESOLVED = "Resolved"
    CLOSED = "Closed"


class TicketCategory(str, Enum):
    """What kind of issue the ticket is about (matches the frontend options)."""

    NETWORK = "Network"
    ACCOUNT = "Account"
    SOFTWARE = "Software"
    EMAIL = "Email"
    HARDWARE = "Hardware"
    OTHER = "Other"


class TicketPriority(str, Enum):
    """How urgent the ticket is (matches the frontend options)."""

    LOW = "Low"
    MEDIUM = "Medium"
    HIGH = "High"


class Ticket(BaseModel):
    """One support ticket.

    NOTE on `id`: unlike conversations/knowledge (which use MongoDB's raw _id),
    tickets use a friendly, human-readable id like "INC-1043" generated by the
    service layer, because that is what employees and the UI display. `id` is
    optional here only so we can build a Ticket before the id is assigned.

    Server-decided fields (id, status, created_at) are set by the backend, never
    by the client. `assignee_*` and `resolved_at` stay empty until an IT admin
    acts on the ticket in a later slice.
    """

    id: str | None = None

    # Who raised it. Sent by the frontend from the signed-in user (works until
    # real authentication exists).
    requester_name: str
    requester_email: str

    # The issue itself.
    subject: str
    category: TicketCategory = TicketCategory.OTHER
    priority: TicketPriority = TicketPriority.MEDIUM
    description: str

    # Lifecycle. New tickets start OPEN; the server sets this, not the client.
    status: TicketStatus = TicketStatus.OPEN

    # Filled in later by an IT admin (admin slice). Optional for now.
    assignee_name: str | None = None
    assignee_email: str | None = None
    resolved_at: datetime | None = None

    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
